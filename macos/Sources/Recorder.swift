import AppKit
import CoreServices

/// Ce qui alimente la mémoire : applis utilisées, presse-papiers, fichiers créés / modifiés / ouverts, téléchargements.
@MainActor
final class Recorder {
    let store: Store
    let settings: MemoSettings
    var onChange: (() -> Void)?
    /// Dossier où sont rangées les images copiées (miniatures).
    let clipsDir: URL

    private var observers: [NSObjectProtocol] = []
    private var clipTimer: Timer?
    private var purgeTimer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ignoreChangeCount: Int?
    private var lastClip: (id: Int64, text: String, at: Date)?
    private var current: (id: Int64, name: String, start: Date)?
    private var stream: FSEventStreamRef?
    private var query: NSMetadataQuery?
    private var lastOpened: [String: Date] = [:]
    private let startedAt = Date()
    private let myBundleID = Bundle.main.bundleIdentifier ?? "fr.aikographic.aikomemo"

    init(store: Store, settings: MemoSettings, clipsDir: URL) {
        self.store = store
        self.settings = settings
        self.clipsDir = clipsDir
        try? FileManager.default.createDirectory(at: clipsDir, withIntermediateDirectories: true)
    }

    var recording: Bool { !settings.isPaused }

    var frontApp: NSRunningApplication? { NSWorkspace.shared.frontmostApplication }
    var frontAppName: String? { frontApp?.localizedName }
    var frontIsExcluded: Bool {
        guard let id = frontApp?.bundleIdentifier else { return false }
        return settings.excludedBundleIDs.contains(id)
    }

    func start() {
        let ws = NSWorkspace.shared.notificationCenter
        observers.append(ws.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil,
                                        queue: .main) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            MainActor.assumeIsolated { self?.activated(app) }
        })
        for name in [NSWorkspace.willSleepNotification, NSWorkspace.sessionDidResignActiveNotification,
                     NSWorkspace.screensDidSleepNotification] {
            observers.append(ws.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.closeSession() }
            })
        }
        activated(frontApp)

        let t = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.pollClipboard() }
        }
        RunLoop.main.add(t, forMode: .common)
        clipTimer = t

        startFileWatching()
        startOpenedQuery()

        purge()
        let p = Timer(timeInterval: 3600, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.purge() }
        }
        RunLoop.main.add(p, forMode: .common)
        purgeTimer = p
    }

    func stop() {
        closeSession()
        observers.forEach { NSWorkspace.shared.notificationCenter.removeObserver($0) }
        observers.removeAll()
        clipTimer?.invalidate()
        purgeTimer?.invalidate()
        stopFileWatching()
        query?.stop()
        query = nil
    }

    func purge() {
        let limit = Date().addingTimeInterval(-Double(settings.retentionDays) * 86400)
        for path in store.purge(olderThan: limit) { try? FileManager.default.removeItem(atPath: path) }
    }

    func eraseAll() {
        store.deleteAll()
        try? FileManager.default.removeItem(at: clipsDir)
        try? FileManager.default.createDirectory(at: clipsDir, withIntermediateDirectories: true)
        current = nil
        lastClip = nil
        onChange?()
    }

    // MARK: - Applis

    private func activated(_ app: NSRunningApplication?) {
        closeSession()
        guard recording, settings.recordApps, let app, let name = app.localizedName,
              let id = app.bundleIdentifier, id != myBundleID, !settings.excludedBundleIDs.contains(id) else { return }
        let rowID = store.insert(MemoEvent(ts: Date(), kind: .app, title: name, detail: id))
        current = (rowID, name, Date())
    }

    private func closeSession() {
        guard let c = current else { return }
        current = nil
        let seconds = Date().timeIntervalSince(c.start)
        if seconds < 4 { store.delete(c.id) } else { store.setDuration(c.id, seconds) }
    }

    // MARK: - Presse-papiers

    /// À appeler quand AikoMemo remet lui-même quelque chose dans le presse-papiers.
    func ignoreCurrentClipboard() {
        ignoreChangeCount = NSPasteboard.general.changeCount
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.apple.is-remote-clipboard.secret",
    ]

    func pollClipboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        if ignoreChangeCount == pb.changeCount { return }
        guard recording, settings.recordClipboard, !frontIsExcluded else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return }   // mot de passe : jamais enregistré
        let appName = frontAppName

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let names = urls.map(\.lastPathComponent)
            let title = urls.count == 1 ? names[0] : "\(urls.count) fichiers : " + names.prefix(3).joined(separator: ", ")
            store.insert(MemoEvent(ts: Date(), kind: .clipboard, title: title, path: urls[0].path, app: appName,
                                   source: appName, detail: urls.map(\.path).joined(separator: "\n"),
                                   ext: urls.count == 1 ? urls[0].pathExtension.lowercased() : nil))
            onChange?()
            return
        }
        if let text = pb.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty, !Self.looksLikeSecret(trimmed) else { return }
            if let last = lastClip, last.text == trimmed, Date().timeIntervalSince(last.at) < 600 {
                store.touch(last.id, at: Date())
                return
            }
            let first = trimmed.components(separatedBy: .newlines).first ?? trimmed
            let title = first.count > 140 ? String(first.prefix(140)) + "…" : first
            let id = store.insert(MemoEvent(ts: Date(), kind: .clipboard, title: title, app: appName, source: appName,
                                            detail: String(trimmed.prefix(20000))))
            lastClip = (id, trimmed, Date())
            onChange?()
            return
        }
        if let image = NSImage(pasteboard: pb), image.isValid {
            let size = image.size
            let file = clipsDir.appendingPathComponent("\(UUID().uuidString).png")
            if let png = Self.thumbnailPNG(image, maxSide: 900) {
                try? png.write(to: file)
                store.insert(MemoEvent(ts: Date(), kind: .clipboard,
                                       title: "Image copiée (\(Int(size.width))×\(Int(size.height)))",
                                       app: appName, source: appName, detail: "image:" + file.path, ext: "png"))
                onChange?()
            }
        }
    }

    /// Un mot de passe probable : un seul « mot » de 8 à 64 caractères mélangeant lettres, chiffres et symboles.
    static func looksLikeSecret(_ s: String) -> Bool {
        if s.contains(where: \.isWhitespace) { return false }
        if s.lowercased().hasPrefix("http") || s.contains("@") || s.hasPrefix("/") || s.hasPrefix("~") { return false }
        let n = s.count
        if n >= 20 && n <= 200 {
            // Clés d'API connues
            for p in ["sk-", "sk_live_", "sk_test_", "ghp_", "github_pat_", "xox", "AKIA", "AIza", "glpat-", "eyJ"]
                where s.hasPrefix(p) { return true }
        }
        guard (8...64).contains(n) else { return false }
        var classes = 0
        if s.contains(where: \.isLowercase) { classes += 1 }
        if s.contains(where: \.isUppercase) { classes += 1 }
        if s.contains(where: \.isNumber) { classes += 1 }
        if s.contains(where: { !$0.isLetter && !$0.isNumber }) { classes += 1 }
        return classes >= 3 && s.contains(where: \.isNumber)
    }

    static func thumbnailPNG(_ image: NSImage, maxSide: CGFloat) -> Data? {
        let s = image.size
        guard s.width > 0, s.height > 0 else { return nil }
        let k = min(1, maxSide / max(s.width, s.height))
        let w = Int(s.width * k), h = Int(s.height * k)
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h, bitsPerSample: 8,
                                         samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                         colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        image.draw(in: NSRect(x: 0, y: 0, width: w, height: h))
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }

    // MARK: - Fichiers (FSEvents)

    var watchedFolders: [String] {
        if settings.recordFiles { return settings.folders.filter { FileManager.default.fileExists(atPath: $0) } }
        if settings.recordDownloads { return [FileManager.default.homeDirectoryForCurrentUser.path + "/Downloads"] }
        return []
    }

    func restartFileWatching() {
        stopFileWatching()
        startFileWatching()
    }

    private func startFileWatching() {
        let paths = watchedFolders
        guard !paths.isEmpty else { return }
        var ctx = FSEventStreamContext(version: 0, info: Unmanaged.passUnretained(self).toOpaque(),
                                       retain: nil, release: nil, copyDescription: nil)
        let callback: FSEventStreamCallback = { _, info, count, rawPaths, flags, _ in
            guard let info else { return }
            let me = Unmanaged<Recorder>.fromOpaque(info).takeUnretainedValue()
            let list = unsafeBitCast(rawPaths, to: NSArray.self) as? [String] ?? []
            var items: [(String, UInt32)] = []
            for i in 0..<min(count, list.count) { items.append((list[i], flags[i])) }
            MainActor.assumeIsolated { me.handleFileEvents(items) }
        }
        let flags = UInt32(kFSEventStreamCreateFlagFileEvents | kFSEventStreamCreateFlagUseCFTypes
                           | kFSEventStreamCreateFlagNoDefer)
        guard let s = FSEventStreamCreate(nil, callback, &ctx, paths as CFArray,
                                          FSEventStreamEventId(kFSEventStreamEventIdSinceNow), 1.0, flags) else { return }
        FSEventStreamSetDispatchQueue(s, DispatchQueue.main)
        FSEventStreamStart(s)
        stream = s
    }

    private func stopFileWatching() {
        guard let s = stream else { return }
        FSEventStreamStop(s)
        FSEventStreamInvalidate(s)
        FSEventStreamRelease(s)
        stream = nil
    }

    static func isIgnored(_ path: String) -> Bool {
        let name = (path as NSString).lastPathComponent
        if name.hasPrefix(".") || name.hasPrefix("~$") || name == "Icon\r" { return true }
        let lower = name.lowercased()
        for suffix in [".crdownload", ".download", ".part", ".tmp", ".partial", ".swp", ".lock", ".icloud"]
            where lower.hasSuffix(suffix) {
            return true
        }
        for bit in ["/.", "/Library/", "/node_modules/", "/.git/", "/.Trash/", "/__pycache__/", "/DerivedData/",
                    "/.cache/", "/CacheClip/", "/Render Cache/", "/Optimized Media/", "/Proxy Media/",
                    ".app/", ".photoslibrary/", ".fcpbundle/", ".drp_proxies/"] where path.contains(bit) {
            return true
        }
        return false
    }

    func handleFileEvents(_ items: [(String, UInt32)]) {
        guard recording else { return }
        var changed = false
        for (path, flag) in items {
            if Self.isIgnored(path) { continue }
            if flag & UInt32(kFSEventStreamEventFlagItemIsDir) != 0 { continue }
            var isDir: ObjCBool = false
            guard FileManager.default.fileExists(atPath: path, isDirectory: &isDir), !isDir.boolValue else { continue }
            let created = flag & UInt32(kFSEventStreamEventFlagItemCreated) != 0
                || flag & UInt32(kFSEventStreamEventFlagItemRenamed) != 0
            let modified = flag & UInt32(kFSEventStreamEventFlagItemModified) != 0
            if !created && !modified { continue }
            if record(path: path, created: created) { changed = true }
            // Les navigateurs posent l'origine du fichier juste après : on revérifie un peu plus tard
            if created {
                DispatchQueue.main.asyncAfter(deadline: .now() + 3) { [weak self] in
                    MainActor.assumeIsolated { if self?.upgradeToDownload(path) == true { self?.onChange?() } }
                }
            }
        }
        if changed { onChange?() }
    }

    /// Enregistre (ou rafraîchit) un fichier. Renvoie vrai si la mémoire a changé.
    @discardableResult
    func record(path: String, created: Bool) -> Bool {
        let now = Date()
        let url = URL(fileURLWithPath: path)
        let origin = Self.origin(of: path)
        let isDownload = origin != nil
        if !settings.recordFiles && !(isDownload && settings.recordDownloads) { return false }

        if let previous = store.latest(path: path, kinds: [.created, .modified, .download], since: now.addingTimeInterval(-600)) {
            var e = previous
            e.ts = now
            if isDownload, e.kind != .download, settings.recordDownloads {
                e.kind = .download
                e.source = origin?.source
                e.detail = origin?.url
            }
            store.update(e)
            return true
        }
        var kind: EventKind = created ? .created : .modified
        if isDownload && settings.recordDownloads && created { kind = .download }
        if kind == .download || settings.recordFiles {
            store.insert(MemoEvent(ts: now, kind: kind, title: url.lastPathComponent, path: path, app: frontAppName,
                                   source: kind == .download ? origin?.source : nil,
                                   detail: kind == .download ? origin?.url : nil,
                                   ext: url.pathExtension.lowercased()))
            return true
        }
        return false
    }

    private func upgradeToDownload(_ path: String) -> Bool {
        guard settings.recordDownloads, let origin = Self.origin(of: path),
              var e = store.latest(path: path, kinds: [.created, .modified], since: Date().addingTimeInterval(-120))
        else { return false }
        e.kind = .download
        e.source = origin.source
        e.detail = origin.url
        store.update(e)
        return true
    }

    /// Origine d'un fichier téléchargé (adresse et appli qui l'a reçu), lue dans ses attributs étendus.
    static func origin(of path: String) -> (source: String?, url: String?)? {
        let froms = xattr(path, "com.apple.metadata:kMDItemWhereFroms").flatMap {
            try? PropertyListSerialization.propertyList(from: $0, format: nil) as? [String]
        } ?? []
        var agent: String?
        if let q = xattr(path, "com.apple.quarantine"), let s = String(data: q, encoding: .utf8) {
            let parts = s.split(separator: ";", omittingEmptySubsequences: false)
            if parts.count >= 3 { agent = String(parts[2]) }
        }
        if froms.isEmpty && (agent == nil || agent == "") { return nil }
        // Fichiers simplement décompressés ou créés par une appli locale : pas un téléchargement
        if froms.isEmpty, let a = agent, ["Archive Utility", "Utilitaire d’archive", "The Unarchiver"].contains(a) {
            return nil
        }
        return SourceNamer.describe(whereFroms: froms, quarantineAgent: agent)
    }

    static func xattr(_ path: String, _ name: String) -> Data? {
        let size = getxattr(path, name, nil, 0, 0, 0)
        guard size > 0 else { return nil }
        var data = Data(count: size)
        let read = data.withUnsafeMutableBytes { getxattr(path, name, $0.baseAddress, size, 0, 0) }
        return read > 0 ? data : nil
    }

    // MARK: - Fichiers ouverts (Spotlight)

    private func startOpenedQuery() {
        guard settings.recordFiles else { return }
        let q = NSMetadataQuery()
        q.predicate = NSPredicate(format: "kMDItemLastUsedDate >= %@", startedAt as NSDate)
        q.searchScopes = [NSMetadataQueryUserHomeScope]
        q.notificationBatchingInterval = 2
        NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidUpdate, object: q, queue: .main) { [weak self] note in
            let added = note.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem] ?? []
            let changed = note.userInfo?[NSMetadataQueryUpdateChangedItemsKey] as? [NSMetadataItem] ?? []
            let items: [(String, Date)] = (added + changed).compactMap { item in
                guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String,
                      let used = item.value(forAttribute: "kMDItemLastUsedDate") as? Date else { return nil }
                return (path, used)
            }
            MainActor.assumeIsolated { self?.opened(items) }
        }
        q.start()
        query = q
    }

    func opened(_ items: [(String, Date)]) {
        guard recording, settings.recordFiles else { return }
        var changed = false
        for (path, used) in items {
            if Self.isIgnored(path) || path.hasSuffix(".app") || path.contains(".app/") { continue }
            if let last = lastOpened[path], used <= last { continue }
            lastOpened[path] = used
            if let prev = store.latest(path: path, kinds: [.opened], since: used.addingTimeInterval(-300)) {
                var e = prev
                e.ts = used
                store.update(e)
            } else {
                let url = URL(fileURLWithPath: path)
                store.insert(MemoEvent(ts: used, kind: .opened, title: url.lastPathComponent, path: path,
                                       app: frontAppName, ext: url.pathExtension.lowercased()))
            }
            changed = true
        }
        if changed { onChange?() }
    }
}
